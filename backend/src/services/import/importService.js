/**
 * Phase 7F-E — eZee CSV operational data import.
 *
 * eZee CSV -> parse -> normalized rows -> deterministic mapping profile ->
 * row normalization/validation -> Guest upsert -> Stay upsert -> ImportBatch
 * audit -> aggregate result. Operational data lands exclusively in the
 * existing Guest/Stay MongoDB models (via their existing unique partial
 * indexes on externalId/reservationId) — nothing here touches
 * KnowledgeDocument/KnowledgeChunk/embeddings/RAG, calls no LLM, and no
 * Signal is generated by an import (see CLAUDE.md's AI/RAG boundaries and
 * the phase's own design report).
 *
 * Rows are processed sequentially, not in parallel: this is what makes
 * "last row wins" for a duplicate reservationId within one file fall out
 * naturally (each row's upsert sees the previous row's write).
 *
 * Write ordering / partial-write behavior (no transactions on purpose — the
 * dev MongoDB is a standalone instance, and there is no compensation logic):
 *  1. Every validation (mapping, dates, status, unit, immutability, required
 *     new-Stay fields, merged date range, Mongoose schema validate()) runs
 *     BEFORE any write, so a row that fails validation writes nothing.
 *  2. The Guest is saved first, then the Stay. If the Guest save succeeds and
 *     the Stay save then fails (DB-level error only), the Guest remains and
 *     the row is reported failed.
 *  3. Re-running is idempotent: with an externalId the retry finds that Guest
 *     by (workspaceId, externalId) and reuses it — no duplicate Guest — then
 *     creates the Stay. Without one, the just-created keyless Guest is removed
 *     when the Stay save fails, so the retry starts clean. A duplicate-key
 *     race on either save is retried (bounded, up to 5 attempts).
 *
 * Guest identity (7F-F2, option A): guest.externalId is OPTIONAL.
 *  - With an externalId, the Guest is (workspaceId, externalId), as before.
 *  - Without one, identity comes from the reservation: an existing Stay's
 *    linked Guest (Stay.guestId, scoped to the workspace) is updated; a NEW
 *    reservation creates a NEW Guest with no externalId. Returning guests are
 *    therefore NOT merged across reservations — that needs a real guest
 *    identifier. A newly created keyless Guest is removed again if its Stay
 *    save fails, so a retry cannot accumulate orphan Guests (it is the only
 *    compensation in the importer: the Guest was created moments earlier in
 *    the same call and nothing can reference it yet).
 *
 * Design choices (approved in 7F-E review):
 *  - A blank mapped cell never erases an existing non-empty value.
 *  - Imported Stays deliberately do NOT run stayService's manual-entry
 *    overlap/double-booking guard (externally-sourced facts are recorded as
 *    they happened, not rejected by an internal data-entry safeguard).
 */

/** Caps persisted/returned per-row diagnostics so a huge bad file cannot bloat the ImportBatch document or response. */
const MAX_RECORDED_ISSUES = 1000;
const MAX_FILENAME_LENGTH = 255;

/** Basename only, bounded — never persist a client-supplied path. */
function sanitizeFilename(name) {
  const base = String(name ?? "").split(/[\\/]/).pop().replace(/[\u0000-\u001f]/g, "").trim();
  return base.slice(0, MAX_FILENAME_LENGTH);
}

async function resolveUnitId(propertyId, roomNumber) {
  if (roomNumber === undefined || roomNumber === null || roomNumber === "") return undefined;
  // propertyId was already proven to belong to the workspace; a Unit is only
  // ever resolved through that Property, never by unitNumber alone.
  const unit = await Unit.findOne({ propertyId, unitNumber: roomNumber });
  if (!unit) {
    throw new RowError(`Unit not found for property: "${clip(roomNumber)}"`);
  }
  return unit._id;
}

/**
 * Validates everything about one row and builds (but does not save) the
 * Guest/Stay documents, so a row that is going to fail never leaves a
 * partial write behind. Only DB-level failures during the final saves (e.g.
 * a unique-index race) can still interrupt after the first save.
 *
 * Natural keys are always workspace-scoped: (workspaceId, externalId) for
 * Guest, (workspaceId, reservationId) for Stay.
 */
async function processRow({ workspaceId, propertyId, mappingProfile, parseDate, statusMapping, rawRow }) {
  const row = normalizeRow(mapRow(rawRow, mappingProfile), { parseDate, statusMapping });
  if (row.skipped) return { outcome: "skipped" };

  const { reservationId, externalId, checkIn, checkOut, status, adults, children } = row;
  const unitId = await resolveUnitId(propertyId, row.roomNumber);

  const existingStay = await Stay.findOne({ workspaceId, reservationId });
  // Workspace-scoped in both branches: by natural key when the row has an
  // externalId, otherwise through the existing Stay's own guest link.
  let existingGuest = null;
  if (externalId) {
    existingGuest = await Guest.findOne({ workspaceId, externalId });
  } else if (existingStay) {
    existingGuest = await Guest.findOne({ _id: existingStay.guestId, workspaceId });
  }

  if (existingStay) {
    // guestId/propertyId are immutable after creation (same as stayService's
    // UPDATABLE list) — a conflicting row fails loudly instead of either
    // silently rewriting the link or silently ignoring the mismatch.
    if (String(existingStay.propertyId) !== String(propertyId)) {
      throw new RowError("Reservation belongs to a different property");
    }
    if (externalId) {
      if (!existingGuest || String(existingStay.guestId) !== String(existingGuest._id)) {
        throw new RowError("Reservation belongs to a different guest");
      }
    } else if (!existingGuest) {
      throw new RowError("Reservation's guest record was not found");
    }
  } else {
    assertNewStayComplete(row);
    if (!externalId && Object.keys(row.guest).length === 0) {
      // A keyless guest with no details at all would be an empty shell.
      throw new RowError("Missing guest details for a new reservation without guest.externalId");
    }
  }

  const createsKeylessGuest = !existingGuest && !externalId;
  const guest = existingGuest ?? new Guest(externalId ? { workspaceId, externalId } : { workspaceId });
  // Workspace -> Property -> Guest: an imported guest belongs to the property the file was imported for (a guest of another property is never re-pointed).
  if (guest.propertyId && String(guest.propertyId) !== String(propertyId)) throw new RowError("Guest belongs to a different property");
  guest.propertyId = propertyId;
  for (const [field, value] of Object.entries(row.guest)) guest[field] = value;

  const stay = existingStay ?? new Stay({ workspaceId, reservationId, guestId: guest._id, propertyId });
  if (unitId !== undefined) stay.unitId = unitId;
  if (checkIn !== undefined) stay.checkIn = checkIn;
  if (checkOut !== undefined) stay.checkOut = checkOut;
  if (status !== undefined) stay.status = status;
  if (adults !== undefined) stay.adults = adults;
  if (children !== undefined) stay.children = children;

  // Range is checked on the merged result, so a row supplying only one date
  // cannot produce an inverted range against the stored other date.
  if (stay.checkIn && stay.checkOut && stay.checkOut <= stay.checkIn) {
    throw new RowError("checkOut must be after checkIn");
  }

  await guest.validate();
  await stay.validate();

  await guest.save();
  try {
    await stay.save();
  } catch (error) {
    if (createsKeylessGuest) {
      try {
        await Guest.deleteOne({ _id: guest._id, workspaceId });
      } catch {
        // best effort; the original error is what matters
      }
    }
    throw error;
  }

  return { outcome: existingStay ? "updated" : "created", reservationId };
}

/**
 * Bounded retry on a duplicate-key error: it means a concurrent writer just
 * created the same natural key, so re-running the row finds and updates it.
 * Several simultaneous writers can each lose in turn, hence more than one
 * retry — but always bounded, and any other error is never retried.
 */
const MAX_DUPLICATE_KEY_ATTEMPTS = 5;

async function processRowWithRetry(args) {
  for (let attempt = 1; ; attempt += 1) {
    try {
      return await processRow(args);
    } catch (error) {
      if (!isDuplicateKeyError(error) || attempt >= MAX_DUPLICATE_KEY_ATTEMPTS) throw error;
    }
  }
}

function rowErrorMessage(error) {
  if (error instanceof RowError) return error.message;
  if (error instanceof AppError) return error.message;
  if (isDuplicateKeyError(error)) return duplicateKeyMessage(error);
  return "Row could not be processed";
}

export async function importOperationalCsv({
  workspaceId: rawWorkspaceId,
  propertyId: rawPropertyId,
  filename,
  buffer,
  mappingProfile: rawMappingProfile,
  dateFormat,
  statusMapping: rawStatusMapping,
}) {
  // Tenant validation happens first, before the file or any operational
  // collection is touched. The validated locals below are the only ids used
  // for the rest of the import.
  if (typeof rawWorkspaceId !== "string" || typeof rawPropertyId !== "string") {
    throw new AppError("workspaceId and propertyId are required", 400);
  }
  const workspaceId = requireObjectId(rawWorkspaceId, "workspaceId");
  await assertExists(Workspace, workspaceId, "Workspace");

  const propertyId = requireObjectId(rawPropertyId, "propertyId");
  const property = await findInWorkspaceOr404(Property, propertyId, workspaceId, "Property");

  if (!buffer || buffer.length === 0) {
    throw new AppError("Uploaded file is empty", 400);
  }

  let headerRow;
  try {
    [headerRow] = parse(buffer, { bom: true, trim: true, to_line: 1 });
  } catch (error) {
    throw new AppError(`Malformed CSV file (${error.code || "parse error"})`, 400);
  }
  if (!headerRow || headerRow.length === 0) {
    throw new AppError("CSV file has no header row", 400);
  }
  // Resource limits (Phase 21), all configurable (see config/runtimeConfig.js getImportLimits). The whole file is refused,
  // and nothing is written, BEFORE any row is processed. They bound memory and the number of synchronous per-row DB round trips.
  const limits = getImportLimits();
  if (headerRow.length > limits.maxColumns) {
    throw new AppError(`CSV file has more than ${limits.maxColumns} columns`, 400, { code: "IMPORT_LIMIT_COLUMNS" });
  }

  // File-level checks must all pass before any row is touched. Duplicate
  // headers make column mapping ambiguous, so the whole file is rejected here
  // (nothing written, no ImportBatch created).
  assertNoDuplicateHeaders(headerRow);
  const mappingProfile = validateMappingProfile(rawMappingProfile, headerRow);
  // Dates are wall-clock times at the owning Property, in its IANA time zone.
  const parseDate = buildDateParser(dateFormat, property.timezone || "UTC");
  const statusMapping = validateStatusMapping(rawStatusMapping);

  let rows;
  try {
    // `to` stops the parser one record past the limit (so a huge file is never fully materialised); `max_record_size`
    // bounds a single record (a quoted field that never closes cannot swallow the file).
    rows = parse(buffer, { columns: true, bom: true, trim: true, skip_empty_lines: true, to: limits.maxRows + 1, max_record_size: limits.maxRecordBytes });
  } catch (error) {
    if (error.code === "CSV_MAX_RECORD_SIZE") throw new AppError(`A CSV record is larger than ${limits.maxRecordBytes} bytes`, 400, { code: "IMPORT_LIMIT_RECORD" });
    throw new AppError(`Malformed CSV file (${error.code || "parse error"})`, 400);
  }
  if (rows.length > limits.maxRows) {
    throw new AppError(`CSV file has more than ${limits.maxRows} data rows`, 400, { code: "IMPORT_LIMIT_ROWS" });
  }
  for (let index = 0; index < rows.length; index += 1) {
    for (const value of Object.values(rows[index])) {
      if (typeof value === "string" && value.length > limits.maxFieldLength) {
        throw new AppError(`Row ${index + 2}: a field is longer than ${limits.maxFieldLength} characters`, 400, { code: "IMPORT_LIMIT_FIELD" });
      }
    }
  }

  const importBatch = await ImportBatch.create({
    workspaceId,
    propertyId,
    filename: sanitizeFilename(filename),
    sourceType: "csv",
    status: "pending",
    startedAt: new Date(),
    rowsRead: rows.length,
    // The validated/normalized profile (≤12 allowed keys, bounded values), not the raw request object.
    mappingProfile,
  });
  const batchScope = { _id: importBatch._id, workspaceId };

  try {
    const errors = [];
    const warnings = [];
    let rowsCreated = 0;
    let rowsUpdated = 0;
    let rowsSkipped = 0;
    let rowsFailed = 0;
    const seenReservationIds = new Set();

    for (let index = 0; index < rows.length; index += 1) {
      const rowNumber = index + 2; // header occupies line 1

      try {
        const result = await processRowWithRetry({
          workspaceId,
          propertyId,
          mappingProfile,
          parseDate,
          statusMapping,
          rawRow: rows[index],
        });

        if (result.outcome === "skipped") {
          rowsSkipped += 1;
          continue;
        }

        if (seenReservationIds.has(result.reservationId) && warnings.length < MAX_RECORDED_ISSUES) {
          warnings.push(
            `Row ${rowNumber}: duplicate reservationId "${clip(result.reservationId)}" in file — later row takes precedence`,
          );
        }
        seenReservationIds.add(result.reservationId);

        if (result.outcome === "created") rowsCreated += 1;
        else rowsUpdated += 1;
      } catch (error) {
        rowsFailed += 1;
        if (errors.length < MAX_RECORDED_ISSUES) {
          errors.push({ row: rowNumber, message: rowErrorMessage(error) });
        }
      }
    }

    if (rowsFailed > errors.length) {
      warnings.push(`Only the first ${errors.length} of ${rowsFailed} row errors were recorded`);
    }

    const completedAt = new Date();
    // Scoped write by (_id, workspaceId), never by _id alone.
    await ImportBatch.updateOne(batchScope, {
      $set: { status: "completed", completedAt, rowsCreated, rowsUpdated, rowsSkipped, rowsFailed, errors },
    });

    return {
      importBatchId: String(importBatch._id),
      status: "completed",
      rowsRead: rows.length,
      rowsCreated,
      rowsUpdated,
      rowsSkipped,
      rowsFailed,
      errors,
      warnings,
    };
  } catch (fatal) {
    // Unexpected failure outside per-row handling: leave an honest audit
    // trail (failed + completedAt) where possible, then surface the error.
    try {
      await ImportBatch.updateOne(batchScope, { $set: { status: "failed", completedAt: new Date() } });
    } catch {
      // best effort only
    }
    throw fatal;
  }
}

export async function getImportBatchById(id, workspaceId) {
  const scope = requireObjectId(workspaceId, "workspaceId");
  return toPlain(await findInWorkspaceOr404(ImportBatch, requireObjectId(id), scope, "ImportBatch"));
}
